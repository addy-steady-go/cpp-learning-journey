#include<iostream>
using namespace std;
int main(){
	int a = 5;
	int b = 10;
	
	//Operators in C++
	//1- Arithmetic Operators
	
	cout<<a+b<<endl;
	cout<<a-b<<endl;
	cout<<a*b<<endl;
	cout<<a/b<<endl;
	cout<<a%b<<endl;
	cout<<++a<<" "<<++b<<endl;
	cout<<a++<<" "<<b++<<endl;
	cout<<--a<<" "<<--b<<endl;
	cout<<a--<<" "<<b--<<endl;
	cout<<a<<" "<<b<<endl;
	//2-Assignment Operators '='
	
	//3-Comparison Operators
	
	cout<<(a==b)<<endl;
	cout<<(a!=b)<<endl;
	cout<<(a>b)<<endl;
	cout<<(a<b)<<endl;
	cout<<(a>=b)<<endl;
	cout<<(a<=b)<<endl;
	
	//4-Logical Operators
	// &&(Logical AND) , ||(Logical OR) , !(Logical NOT)
	return 0;
}
