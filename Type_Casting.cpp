#include<iostream>
using namespace std;
int main(){
	//Type-Casting --> Done to change the data type of a variable
	
	float a = 45.46;
	float b = 77.77;
	
	cout<<int(a)<<endl;
	
	cout<<(int)b<<endl;
	
	int c = (int)b;
	cout<<c;
	
	//these will change the decimal float data type to integer data type for both numbers.
	
	return 0;
}
